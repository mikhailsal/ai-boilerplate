import pytest

from quality.discovery import FileKind, FileType, detect, shebang_language
from quality.discovery.filetypes import HEAD_BYTES, has_generated_marker

CODE, DOC, CONFIG, ASSET, UNKNOWN = (
    FileKind.CODE,
    FileKind.DOC,
    FileKind.CONFIG,
    FileKind.ASSET,
    FileKind.UNKNOWN,
)


@pytest.mark.parametrize(
    ("path", "expected"),
    [
        ("src/pkg/a.py", FileType(CODE, "python")),
        ("stubs/a.pyi", FileType(CODE, "python")),
        ("web/App.tsx", FileType(CODE, "typescript")),
        ("web/a.mjs", FileType(CODE, "javascript")),
        ("lib/a.dart", FileType(CODE, "dart")),
        ("src/A.php", FileType(CODE, "php")),
        ("bin/run.sh", FileType(CODE, "shell")),
        ("cmd/main.go", FileType(CODE, "go")),
        ("native/x.HPP", FileType(CODE, "c++")),
        ("README.md", FileType(DOC)),
        ("docs/guide.rst", FileType(DOC)),
        ("LICENSE", FileType(DOC)),
        ("Changelog", FileType(DOC)),
        ("pyproject.toml", FileType(CONFIG)),
        ("uv.lock", FileType(CONFIG)),
        ("phpunit.xml.dist", FileType(CONFIG)),
        (".gitignore", FileType(CONFIG)),
        ("Dockerfile", FileType(CONFIG)),
        ("requirements-dev.txt", FileType(CONFIG)),
        ("constraints.in", FileType(CONFIG)),
        ("setup.py", FileType(CONFIG, "python")),
        ("tests/conftest.py", FileType(CONFIG, "python")),
        ("vite.config.ts", FileType(CONFIG, "typescript")),
        ("eslint.config.mjs", FileType(CONFIG, "javascript")),
        ("rector.php", FileType(CONFIG, "php")),
        ("img/logo.PNG", FileType(ASSET)),
        ("web/site.css", FileType(ASSET)),
        ("data.bin", FileType(UNKNOWN)),
        (".env", FileType(UNKNOWN)),
    ],
)
def test_detects_types_from_names(path: str, expected: FileType) -> None:
    assert detect(path) == expected


@pytest.mark.parametrize(
    ("head", "language"),
    [
        (b"#!/usr/bin/env python3\nprint()\n", "python"),
        (b"#!/usr/bin/python3.14 -I\n", "python"),
        (b"#!/usr/bin/env -S node --no-warnings\n", "javascript"),
        (b"#!/usr/bin/env tsx\n", "typescript"),
        (b"#!/bin/bash -eu\n", "shell"),
        (b"#!/usr/bin/php8.4\n", "php"),
        (b"#!/usr/local/bin/dart\n", "dart"),
        (b"#!/usr/bin/ruby\n", "ruby"),
        (b"#!/opt/bin/custom\n", "custom"),
        (b"#!/usr/bin/env\n", None),
        (b"#!\n", None),
        (b"#!/bin/3\n", None),
        (b"plain text\n", None),
    ],
)
def test_shebangs_name_the_language(head: bytes, language: str | None) -> None:
    assert shebang_language(head) == language


def test_extensionless_files_use_the_shebang() -> None:
    assert detect("bin/tool", b"#!/usr/bin/env python3\n") == FileType(CODE, "python")
    assert detect("bin/tool", b"\x7fELF") == FileType(UNKNOWN)


def test_a_known_extension_wins_over_the_shebang() -> None:
    assert detect("notes.md", b"#!/bin/sh\n") == FileType(DOC)


@pytest.mark.parametrize(
    ("head", "generated"),
    [
        (b"# @generated by protoc\n", True),
        (b"// Code generated by sqlc. DO NOT EDIT.\n", True),
        (b"# Auto-generated file\n", True),
        (b"// GENERATED CODE - DO NOT MODIFY BY HAND\n\npart of 'model.dart';\n", True),
        (b"def generate():\n", False),
        (b" " * HEAD_BYTES + b"@generated", False),
    ],
    ids=["generated", "go-style", "auto", "build-runner", "unrelated", "too-late"],
)
def test_generated_markers_are_read_from_the_header(head: bytes, generated: bool) -> None:
    assert has_generated_marker(head) is generated
