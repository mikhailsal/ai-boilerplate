import pytest

from quality.discovery import FileRecord, Region, classify, detect, owner, region_of
from quality.discovery.classify import Classified
from quality.policy import Category, Policy
from quality.testkit.policies import ComponentSpec, build_policy, classification_toml

WEB = ComponentSpec(id="web", root="apps/web", profile="typescript", source=("src",))


def run(policy: Policy, path: str, head: bytes = b"") -> Classified:
    return classify(policy, path, detect(path, head), head)


def rules_of(found: Classified) -> list[str]:
    return [d.rule for d in found.diagnostics]


def test_the_most_specific_root_owns_a_path() -> None:
    policy = build_policy(ComponentSpec(), WEB)
    assert owner(policy, "apps/web/src/a.ts") == policy.components[1]
    assert owner(policy, "apps/website/a.ts") == policy.components[0]
    assert owner(build_policy(WEB), "src/a.py") is None


def test_regions_follow_declared_roots() -> None:
    policy = build_policy(WEB)
    web = policy.components[0]
    assert region_of(web, "apps/web/src/a.ts") is Region.SOURCE
    assert region_of(web, "apps/web/tests/a.test.ts") is Region.TESTS
    assert region_of(web, "apps/web/README.md") is Region.OTHER
    assert region_of(None, "a.ts") is Region.OTHER


@pytest.mark.parametrize(
    ("path", "category", "region"),
    [
        ("src/pkg/a.py", Category.SOURCE, Region.SOURCE),
        ("src/pkg/README.md", Category.DOCS, Region.SOURCE),
        ("tests/test_a.py", Category.TESTS, Region.TESTS),
        ("tests/data/blob.bin", Category.TESTS, Region.TESTS),
        ("README.md", Category.DOCS, Region.OTHER),
        ("pyproject.toml", Category.CONFIG, Region.OTHER),
        ("setup.py", Category.CONFIG, Region.OTHER),
        ("img/logo.png", Category.ASSETS, Region.OTHER),
    ],
)
def test_natural_categories(path: str, category: Category, region: Region) -> None:
    found = run(build_policy(), path)
    assert found.diagnostics == []
    assert found.record == FileRecord(
        path=path,
        category=category,
        component="app",
        language=detect(path).language,
        region=region,
    )


@pytest.mark.parametrize(
    ("path", "rule", "message"),
    [
        ("data.bin", "discovery.unclassified", "file type cannot be determined"),
        ("src/a.go", "discovery.unsupported-language", "go code has no supported profile"),
        ("src/a.ts", "discovery.language-mismatch", "typescript file in python component 'app'"),
        (
            "scripts/a.py",
            "discovery.unowned-source",
            "python code outside the source and test roots of 'app'",
        ),
    ],
)
def test_natural_findings(path: str, rule: str, message: str) -> None:
    found = run(build_policy(), path)
    assert [(d.rule, d.message) for d in found.diagnostics] == [(rule, message)]
    assert found.diagnostics[0].location is not None
    assert found.diagnostics[0].location.path == path


def test_code_outside_every_component_is_unowned() -> None:
    found = run(build_policy(WEB), "tools/x.py")
    assert [(d.rule, d.message, d.component) for d in found.diagnostics] == [
        ("discovery.unowned-source", "python code outside every component", None)
    ]


def test_extensionless_scripts_are_classified_by_shebang() -> None:
    found = run(build_policy(), "bin/deploy", b"#!/bin/sh\nexit 0\n")
    assert rules_of(found) == ["discovery.unsupported-language"]


def test_vendor_classification_admits_unsupported_code() -> None:
    policy = build_policy(extra=classification_toml("vendor/**", "vendor"))
    found = run(policy, "vendor/lib/x.c")
    assert found.diagnostics == []
    assert found.patterns == ["vendor/**"]
    assert found.record.category is Category.VENDOR
    assert found.record.explicit


def test_fixtures_in_test_roots_can_be_classified() -> None:
    policy = build_policy(extra=classification_toml("tests/fixtures/**", "assets"))
    found = run(policy, "tests/fixtures/broken.py")
    assert found.record.category is Category.ASSETS
    assert found.record.region is Region.TESTS


def test_source_files_cannot_be_relabelled() -> None:
    policy = build_policy(extra=classification_toml("src/pkg/big.py", "vendor"))
    found = run(policy, "src/pkg/big.py")
    assert rules_of(found) == ["discovery.classification-relabel"]
    assert found.record.category is Category.SOURCE
    assert not found.record.explicit


def test_generated_source_needs_a_marker() -> None:
    policy = build_policy(extra=classification_toml("src/pkg/gen/**", "generated"))
    unmarked = run(policy, "src/pkg/gen/api.py", b"x = 1\n")
    marked = run(policy, "src/pkg/gen/api.py", b"# @generated by openapi\n")
    assert rules_of(unmarked) == ["discovery.classification-relabel"]
    assert marked.diagnostics == []
    assert marked.record.category is Category.GENERATED


def test_overlapping_classifications_conflict_and_fall_back() -> None:
    extra = classification_toml("vendor/**", "vendor") + classification_toml(
        "vendor/x/*.c", "generated"
    )
    found = run(build_policy(extra=extra), "vendor/x/a.c")
    assert rules_of(found) == [
        "discovery.classification-conflict",
        "discovery.unsupported-language",
    ]
    assert found.patterns == ["vendor/**", "vendor/x/*.c"]
    assert not found.record.explicit
