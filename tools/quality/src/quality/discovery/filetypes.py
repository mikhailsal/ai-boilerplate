"""File types from names, extensions, and shebangs; no content is executed."""

from __future__ import annotations

import re
from dataclasses import dataclass
from enum import StrEnum
from pathlib import PurePosixPath

from quality.policy import Profile

HEAD_BYTES = 1024


class FileKind(StrEnum):
    """What a file is, before ownership decides its category."""

    CODE = "code"
    DOC = "doc"
    CONFIG = "config"
    ASSET = "asset"
    GENERATED = "generated"
    UNKNOWN = "unknown"


@dataclass(frozen=True, slots=True)
class FileType:
    """A detected kind; code and code-like configuration carry a language."""

    kind: FileKind
    language: str | None = None


PROFILE_LANGUAGES: dict[Profile, frozenset[str]] = {
    Profile.PYTHON: frozenset({"python"}),
    Profile.TYPESCRIPT: frozenset({"typescript", "javascript"}),
    Profile.DART: frozenset({"dart"}),
    Profile.PHP: frozenset({"php"}),
}
SUPPORTED_LANGUAGES = frozenset(lang for langs in PROFILE_LANGUAGES.values() for lang in langs)

CODE_EXTENSIONS = {
    **dict.fromkeys((".py", ".pyi"), "python"),
    **dict.fromkeys((".ts", ".tsx", ".mts", ".cts"), "typescript"),
    **dict.fromkeys((".js", ".jsx", ".mjs", ".cjs"), "javascript"),
    ".dart": "dart",
    ".php": "php",
    **dict.fromkeys((".sh", ".bash", ".zsh", ".fish", ".ksh"), "shell"),
    **dict.fromkeys((".ps1", ".psm1"), "powershell"),
    **dict.fromkeys((".bat", ".cmd"), "batch"),
    **dict.fromkeys((".c", ".h"), "c"),
    **dict.fromkeys((".cc", ".cpp", ".cxx", ".hh", ".hpp", ".hxx"), "c++"),
    **dict.fromkeys((".kt", ".kts"), "kotlin"),
    **dict.fromkeys((".m", ".mm"), "objective-c"),
    **dict.fromkeys((".ex", ".exs"), "elixir"),
    **dict.fromkeys((".pl", ".pm"), "perl"),
    **{
        ext: ext[1:]
        for ext in (".go", ".rs", ".java", ".scala", ".swift", ".lua", ".rb", ".zig", ".nim")
    },
    **{ext: ext[1:] for ext in (".cs", ".fs", ".vb", ".r", ".jl", ".erl", ".hs", ".clj")},
    **{ext: ext[1:] for ext in (".groovy", ".vue", ".svelte", ".elm", ".ml", ".cr")},
}
DOC_EXTENSIONS = frozenset({".md", ".markdown", ".rst", ".txt", ".adoc"})
DOC_STEMS = frozenset(
    {"LICENSE", "LICENCE", "COPYING", "NOTICE", "AUTHORS", "CHANGELOG", "CONTRIBUTORS"}
)
CONFIG_EXTENSIONS = frozenset(
    {".toml", ".yaml", ".yml", ".json", ".jsonc", ".json5", ".ini", ".cfg", ".conf"}
    | {".lock", ".xml", ".neon", ".dist", ".properties", ".sql", ".example"}
)
CONFIG_NAMES = frozenset(
    {".gitignore", ".gitattributes", ".gitmodules", ".gitkeep", ".mailmap", ".editorconfig"}
    | {".npmrc", ".nvmrc", ".node-version", ".python-version", ".tool-versions", ".pubignore"}
    | {".prettierrc", ".prettierignore", ".eslintignore", ".dockerignore", "py.typed"}
    | {"Dockerfile", "Makefile", "CODEOWNERS", "Procfile"}
)
CONFIG_SCRIPTS = {
    **dict.fromkeys(("setup.py", "noxfile.py", "conftest.py"), "python"),
    **dict.fromkeys((".php-cs-fixer.php", ".php-cs-fixer.dist.php", "rector.php"), "php"),
}
CONFIG_SCRIPT_PATTERN = re.compile(r"^[\w.-]+\.config\.(?:[cm]?js|[cm]?ts)$")
CONFIG_NAME_PATTERN = re.compile(r"^(?:requirements|constraints)[\w.-]*\.(?:txt|in)$")
ASSET_EXTENSIONS = frozenset(
    {".png", ".jpg", ".jpeg", ".gif", ".svg", ".ico", ".webp", ".bmp", ".tif", ".tiff", ".avif"}
    | {".woff", ".woff2", ".ttf", ".otf", ".eot", ".mp3", ".mp4", ".wav", ".ogg", ".webm"}
    | {".pdf", ".csv", ".tsv", ".css", ".scss", ".sass", ".less", ".styl", ".html", ".htm"}
)
# Source maps are written by compilers and bundlers only.
GENERATED_EXTENSIONS = frozenset({".map"})
# The extension sets are disjoint, so one table holds the kinds without a language.
SUFFIX_KINDS = {
    **dict.fromkeys(CONFIG_EXTENSIONS, FileKind.CONFIG),
    **dict.fromkeys(ASSET_EXTENSIONS, FileKind.ASSET),
    **dict.fromkeys(GENERATED_EXTENSIONS, FileKind.GENERATED),
}
INTERPRETERS = {
    "python": "python",
    "node": "javascript",
    "nodejs": "javascript",
    "tsx": "typescript",
    "ts-node": "typescript",
    "dart": "dart",
    "php": "php",
    **dict.fromkeys(("sh", "bash", "dash", "zsh", "ksh", "fish"), "shell"),
    "perl": "perl",
    "ruby": "ruby",
}
# `generated code` matches the header of Dart's build_runner:
# `// GENERATED CODE - DO NOT MODIFY BY HAND`.
GENERATED_MARKER = re.compile(
    rb"@generated|do not edit|code generated|generated code|auto-?generated|generated by",
    re.IGNORECASE,
)


def _script_language(name: str) -> str | None:
    if name in CONFIG_SCRIPTS:
        return CONFIG_SCRIPTS[name]
    if CONFIG_SCRIPT_PATTERN.match(name):
        return "typescript" if name.endswith("ts") else "javascript"
    return None


def shebang_language(head: bytes) -> str | None:
    """Return the language named by a `#!` line, following `env` and its options."""
    if not head.startswith(b"#!"):
        return None
    words = head[2:].split(b"\n", 1)[0].decode("utf-8", errors="replace").split()
    if words and PurePosixPath(words[0]).name == "env":
        words = [word for word in words[1:] if not word.startswith("-")]
    if not words:
        return None
    program = re.sub(r"[\d.]+$", "", PurePosixPath(words[0]).name)
    return INTERPRETERS.get(program, program or None)


def _by_name(name: str) -> FileType | None:
    suffix = PurePosixPath(name).suffix.lower()
    script = _script_language(name)
    if name in CONFIG_NAMES or CONFIG_NAME_PATTERN.match(name) or script is not None:
        return FileType(FileKind.CONFIG, script)
    if suffix in CODE_EXTENSIONS:
        return FileType(FileKind.CODE, CODE_EXTENSIONS[suffix])
    if suffix in DOC_EXTENSIONS or (not suffix and name.upper() in DOC_STEMS):
        return FileType(FileKind.DOC)
    kind = SUFFIX_KINDS.get(suffix)
    return None if kind is None else FileType(kind)


def detect(path: str, head: bytes = b"") -> FileType:
    """Detect a file type from its path and, for extensionless files, its first bytes."""
    found = _by_name(PurePosixPath(path).name)
    if found is not None:
        return found
    language = shebang_language(head)
    return FileType(FileKind.CODE, language) if language else FileType(FileKind.UNKNOWN)


def has_generated_marker(head: bytes) -> bool:
    """Return whether the first bytes of a file declare it as generated."""
    return GENERATED_MARKER.search(head[:HEAD_BYTES]) is not None
