"""PHPUnit with Xdebug branch coverage, configured by the gate (decision 0013).

Every suite runs the component's locked PHPUnit with a configuration the gate
writes into the run's output directory; the component's own phpunit.xml is not
read. The configuration names one test suite with the suite's existing roots,
where files ending in `Test.php` are tests, and a bootstrap file, also
generated. The bootstrap loads the component's Composer autoloader and then
every source file that only declares classes, functions, and constants, so a
file no test loads is still compiled. A file that runs code when it is loaded
is left to the tests.

Unit suites also collect coverage. The configuration's source filter is every
`.php` file of the source roots without the test roots and `vendor/`, uncovered
files included, with branch coverage on and `@codeCoverageIgnore` disabled.
PHPUnit writes Clover for the branches and its JSONL report for the lines,
because Clover hides the statement of a one-line method behind the method's
record (decision 0005); the engine reads the Clover file and the profile the
JSONL directory beside it. Xdebug runs in coverage mode, loaded with
`-d zend_extension=xdebug` unless the system loads it; PHPUnit refuses to
start when no driver supports branch coverage, so PCOV and phpdbg cannot stand
in for it. Xdebug measures the branches of a file only when the file is
compiled, so after a run each source file with named functions or methods but
no branch in the report is marked as unmeasured, which fails the gate.

Every run writes JUnit XML, in which an incomplete test is skipped, and gets a
new home, cache, and temporary directory, as for the other profiles. A run that
writes no results could not run at all, and neither could one that leaves an
empty results file, as PHPUnit does when it refuses to start; the failure
quotes PHPUnit's reason. A unit suite reaches loopback only where the system
allows it (decision 0008). PHPUnit exits 1 when a test failed and 2 when one
raised an error.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from dataclasses import replace
from pathlib import Path, PurePosixPath
from types import MappingProxyType
from xml.sax.saxutils import escape, quoteattr

from quality.adapters.native import fail, failure, suite_command
from quality.adapters.php.runtime import Php
from quality.adapters.php.structure import PhpFile
from quality.coverage import CoverageReport
from quality.process import Command, ProcessError, run
from quality.testing import ResultsFormat, Suite, SuiteRequest, SuiteRun

SUITE_TIMEOUT = 3600.0
TOOL = "phpunit"
FAILURE_STATUS = frozenset({1, 2})
BINARY = "vendor/phpunit/phpunit/phpunit"
VENDOR = "vendor"
CONFIGURATION = "phpunit.xml"
BOOTSTRAP = "bootstrap.php"
RESULTS = "junit.xml"
CLOVER = "clover.xml"
JSONL = "coverage-jsonl"
JSONL_FILES = ("meta.json", "coverage.jsonl", "tests.jsonl")
TESTS = "Test.php"


def source_files(request: SuiteRequest) -> tuple[str, ...]:
    """Return the PHP files of the source roots, without test roots and `vendor/`."""
    component = request.component
    skipped = [PurePosixPath(component.root, root) for root in component.tests.all_paths()]
    skipped.append(PurePosixPath(component.root, VENDOR))
    found: set[str] = set()
    for root in component.source:
        for path in (request.directory / root).rglob("*.php"):
            name = PurePosixPath(path.relative_to(request.snapshot).as_posix())
            if not path.is_symlink() and not any(name.is_relative_to(base) for base in skipped):
                found.add(name.as_posix())
    return tuple(sorted(found))


def _literal(path: Path) -> str:
    """Return a path as a single-quoted PHP string."""
    text = str(path).replace("\\", "\\\\").replace("'", "\\'")
    return f"'{text}'"


def bootstrap(request: SuiteRequest, files: Iterable[PhpFile]) -> Path:
    """Write the bootstrap that loads the autoloader and every file that only declares."""
    loaded = [request.snapshot / file.path for file in files if file.loadable]
    autoloader = request.directory / VENDOR / "autoload.php"
    lines = [f"require_once {_literal(path)};\n" for path in (autoloader, *loaded)]
    header = (
        "<?php\n\n// Generated by the quality gate: the autoloader, then every declaring file.\n"
    )
    path = request.output / BOOTSTRAP
    path.write_text(header + "".join(lines), encoding="utf-8")
    return path


def _entries(tag: str, paths: Iterable[Path], suffix: str) -> str:
    attribute = f" suffix={quoteattr(suffix)}" if suffix else ""
    return "".join(f"<{tag}{attribute}>{escape(str(path))}</{tag}>" for path in paths)


def _tests(request: SuiteRequest) -> str:
    roots = [request.directory / root for root in request.roots]
    directories = _entries("directory", (root for root in roots if root.is_dir()), TESTS)
    files = _entries("file", (root for root in roots if root.is_file()), "")
    suite = f"<testsuite name={quoteattr(str(request.suite))}>{directories}{files}</testsuite>"
    return f"<testsuites>{suite}</testsuites>"


def _source(request: SuiteRequest) -> str:
    component = request.component
    included = _entries(
        "directory", (request.directory / root for root in component.source), ".php"
    )
    tests = (request.directory / root for root in component.tests.all_paths())
    excluded = _entries("directory", (*tests, request.directory / VENDOR), "")
    return f"<source><include>{included}</include><exclude>{excluded}</exclude></source>"


def configuration(request: SuiteRequest, loader: Path) -> Path:
    """Write the PHPUnit configuration of one suite."""
    attributes = {
        "bootstrap": str(loader),
        "cacheDirectory": str(request.output / "cache"),
        "colors": "false",
        "recordTestRunHistory": "false",
    }
    settings = " ".join(f"{name}={quoteattr(value)}" for name, value in attributes.items())
    coverage = (
        '<coverage includeUncoveredFiles="true" branchCoverage="true" '
        'disableCodeCoverageIgnore="true" ignoreDeprecatedCodeUnits="false"/>'
    )
    body = _tests(request) + (_source(request) + coverage if request.suite is Suite.UNIT else "")
    path = request.output / CONFIGURATION
    path.write_text(
        f'<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by the quality gate. -->\n'
        f"<phpunit {settings}>{body}</phpunit>\n",
        encoding="utf-8",
    )
    return path


def suite_argv(php: Php, request: SuiteRequest, settings: Path) -> tuple[str, ...]:
    """Return the PHPUnit command of one suite; only unit runs collect coverage."""
    unit = request.suite is Suite.UNIT
    reports = (
        f"--coverage-clover={request.output / CLOVER}",
        f"--coverage-jsonl={request.output / JSONL}",
    )
    coverage = reports if unit else ()
    return php.command(
        str(request.directory / BINARY),
        f"--configuration={settings}",
        f"--log-junit={request.output / RESULTS}",
        "--no-progress",
        *coverage,
        coverage=unit,
    )


def run_phpunit(php: Php, request: SuiteRequest, files: Iterable[PhpFile]) -> SuiteRun:
    """Run one suite; a run that leaves no or empty results could not run at all."""
    if not request.roots:
        fail(TOOL, f"the {request.suite} suite of '{request.component.id}' has no roots")
    settings = configuration(request, bootstrap(request, files))
    home = request.output.parent / f"{request.output.name}-home"
    temporary, cache = home / "tmp", home / ".cache"
    temporary.mkdir(parents=True)
    cache.mkdir()
    extra = {"TMPDIR": str(temporary), "XDG_CACHE_HOME": str(cache), "CI": "1"}
    unit = request.suite is Suite.UNIT
    env = php.environ(home, extra, coverage=unit)
    argv, unisolated = suite_command(request, suite_argv(php, request, settings))
    command = Command(argv, cwd=request.directory, timeout=SUITE_TIMEOUT, env=env, reap=True)
    try:
        completed = run(command)
    except ProcessError as error:
        raise failure(TOOL, str(error)) from error
    results = request.output / RESULTS
    if not results.is_file() or not results.stat().st_size:
        output = completed.stderr_text().strip() or completed.stdout_text().strip()
        fail(TOOL, f"exit status {completed.returncode} without test results: {output}")
    clover = request.output / CLOVER
    return SuiteRun(
        completed.returncode,
        results,
        clover if unit and clover.is_file() else None,
        results_format=ResultsFormat.JUNIT,
        unisolated=unisolated,
        failure_status=FAILURE_STATUS,
    )


def unmeasured(report: CoverageReport, units: Mapping[str, int]) -> CoverageReport:
    """Mark each file with functions or methods but no measured branch as unmeasured."""
    files = {
        path: replace(file, branches_measured=False)
        if units.get(path, 0) and not file.branches.total
        else file
        for path, file in report.files.items()
    }
    return replace(report, files=MappingProxyType(files))
